"""Generate vulture_whitelist.py (#1389) from vulture's 60 % output, grouped by reason.

Usage (from the repo root, with the CI's vulture version, see requirements-lint.txt):
    vulture api mcp embeddings ner watchdog alerting --exclude "*/tests/*" \
        --ignore-decorators "@router.*,@router_v1.*,@app.*,@mcp.*,@pytest.*,@field_validator,@model_validator,@validator" \
        --min-confidence 60 > vulture-60.txt
    python scripts/vulture_whitelist.py . vulture-60.txt > vulture_whitelist.py

Only two kinds of finding are accepted: fields of pydantic models (checked by inheritance from BaseModel or
BaseSettings, also across modules) and the framework cases named in FRAMEWORK below. Anything else makes this
script fail: that is code to look at by hand (delete it, wire it, or add it to FRAMEWORK with its reason).
"""

import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")  # vulture reads the whitelist as UTF-8 (Windows would write cp1252)
ROOT = Path(sys.argv[1])
PYDANTIC = {"BaseModel", "BaseSettings"}

FRAMEWORK = {
    ("api/rate_limit.py", "dispatch"): "Starlette calls dispatch() of a BaseHTTPMiddleware on every request.",
    ("api/search.py", "reranker_score"): (
        "SearchResult field (search.py:1089) that search.py fills after the reranker and that goes out in the "
        "JSON response (read by the MCP and the ordering tests)."
    ),
}

bases, trees = {}, {}
for f in ROOT.rglob("*.py"):
    if "tests" in f.parts or ".venv" in f.parts:
        continue
    try:
        tree = ast.parse(f.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        continue
    trees[f.resolve()] = tree
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            bases.setdefault(node.name, set()).update(
                b.id if isinstance(b, ast.Name) else b.attr if isinstance(b, ast.Attribute) else "" for b in node.bases
            )


def is_pydantic(name, seen=()):
    if name in PYDANTIC:
        return True
    if name in seen or name not in bases:
        return False
    return any(is_pydantic(b, seen + (name,)) for b in bases[name])


def enclosing_class(tree, line):
    best = None
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.lineno <= line <= (node.end_lineno or node.lineno):
            if best is None or node.lineno > best.lineno:
                best = node
    return best


fields = defaultdict(set)  # name -> {"file Class"}
framework = defaultdict(set)
other = []
for raw in open(sys.argv[2], encoding="utf-8"):
    m = re.match(r"^(.+?):(\d+): (unused \w+) '([^']+)'", raw.strip())
    if not m:
        continue
    path, line, kind, name = m.group(1).replace("\\", "/"), int(m.group(2)), m.group(3), m.group(4)
    tree = trees.get((ROOT / path).resolve())
    cls = enclosing_class(tree, line) if tree else None
    if kind == "unused variable" and cls is not None and is_pydantic(cls.name):
        fields[name].add(f"{path} {cls.name}")
    elif (path, name) in FRAMEWORK:
        framework[(path, name)].add(line)
    else:
        other.append(raw.strip())

if other:
    sys.exit("findings that are neither pydantic fields nor named framework cases, look at them by hand:\n" + "\n".join(other))

print("""# vulture whitelist (#1389): what vulture thinks is dead and is NOT.
# vulture only READS this file (it is never run or imported): every name here counts as «used».
# Generated by scripts/vulture_whitelist.py, which refuses any finding that is not a pydantic field or a named
# framework case. Do not edit it by hand: regenerate it.
# CAVEAT: vulture counts by name. A name here (e.g. «status») hides a dead variable with the same name elsewhere.
# That is the price of whitelisting pydantic fields, and why nothing else goes in.

# Framework: called by the framework, not by our code.""")
for (path, name), lines in sorted(framework.items()):
    print(f"_.{name}  # {path}:{','.join(map(str, sorted(lines)))}: {FRAMEWORK[(path, name)]}")
print("""
# Fields of pydantic models (inherit from BaseModel or BaseSettings): FastAPI reads them when it validates the
# request and serializes the response (model_dump), and vulture does not see those reads.""")
for name in sorted(fields):
    print(f"_.{name}  # {'; '.join(sorted(fields[name]))}")
